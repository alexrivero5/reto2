package reto2;



public class funciones1 {

	//pasar de millas a kilometros
	public static double millasAKilometros(double n) {
		return n * 1.60934;
	}
	//pasar de kilometros a millas
	public static double kilometrosAMillas(double n) {
		return n / 1.60934;
	}
	//pasar de kilometros a libras
	public static double kilogramosALibras(double n) {
		return n * 2.20462;
	}
	//pasar de libras a kilogramos
	public static double LibrasAKilogramos(double n) {
		return n / 2.20462;
	}
	


}

